//! Keeps `web/src/protocol.gen.ts` in step with the core's wire types.
//!
//! The TypeScript comes from the core's serde types through ts-rs (the core's
//! `ts` feature, enabled only here as a dev-dependency), so every serde
//! attribute on them (`tag`, `rename_all`, `default`, `skip_serializing_if`,
//! `flatten`, `Option`) shapes the output. Regenerate after any change to the
//! wire types or `PROTOCOL_VERSION` with the command in `REGENERATE`.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::path::PathBuf;

use pieceoff_core::{ClientMessage, PROTOCOL_VERSION, ServerMessage};
use pieceoff_web_wasm::{client_message_types, server_message_types};
use ts_rs::{Config, TS, TypeVisitor};

const REGENERATE: &str =
    "PIECEOFF_UPDATE_PROTOCOL=1 cargo test -p pieceoff-web-wasm --test protocol_gen";

fn gen_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/protocol.gen.ts")
}

/// Every declared type reachable from the roots, keyed by TypeScript name so
/// the output order is stable.
struct Collect<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Collect<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Primitives and std containers have no declaration of their own;
        // their element types are still visited through the owning field.
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let mut decl = T::docs().unwrap_or_default();
        decl.push_str("export ");
        decl.push_str(&T::decl(self.cfg));
        let name = T::ident(self.cfg);
        assert!(
            self.decls.insert(name.clone(), decl).is_none(),
            "two wire types are both named {name} in TypeScript"
        );
        T::visit_dependencies(self);
    }
}

fn string_list(name: &str, items: &[String]) -> String {
    let body: Vec<String> = items
        .iter()
        .map(|item| format!("  \"{item}\",\n"))
        .collect();
    format!("export const {name} = [\n{}] as const;\n", body.concat())
}

fn generate() -> String {
    // JSON numbers, not bigint: every u64 on the wire is a millisecond time,
    // a revision or a count, far below 2^53.
    let cfg = Config::new().with_large_int("number");
    let mut collect = Collect {
        cfg: &cfg,
        seen: HashSet::new(),
        decls: BTreeMap::new(),
    };
    collect.visit::<ClientMessage>();
    collect.visit::<ServerMessage>();

    let mut out = String::new();
    out.push_str("// @generated by crates/pieceoff-web-wasm/tests/protocol_gen.rs from the\n");
    out.push_str("// pieceoff-core serde types. Do not edit by hand. Regenerate with:\n");
    out.push_str(&format!("//   {REGENERATE}\n\n"));
    out.push_str("/** The protocol version these types describe. */\n");
    out.push_str(&format!(
        "export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n\n"
    ));
    for decl in collect.decls.values() {
        out.push_str(decl);
        out.push_str("\n\n");
    }
    out.push_str("/** Every `type` tag of `ClientMessage`, as serde names them. */\n");
    out.push_str(&string_list(
        "CLIENT_MESSAGE_TYPES",
        &client_message_types(),
    ));
    out.push('\n');
    out.push_str("/** Every `type` tag of `ServerMessage`, as serde names them. */\n");
    out.push_str(&string_list(
        "SERVER_MESSAGE_TYPES",
        &server_message_types(),
    ));
    // ts-rs leaves a space before each line break it puts after a doc comment.
    let lines: Vec<&str> = out.lines().map(str::trim_end).collect();
    lines.join("\n") + "\n"
}

#[test]
fn protocol_gen_is_current() {
    let fresh = generate();
    let path = gen_path();
    if std::env::var_os("PIECEOFF_UPDATE_PROTOCOL").is_some() {
        std::fs::write(&path, &fresh).expect("write web/src/protocol.gen.ts");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == fresh,
        "web/src/protocol.gen.ts is missing or out of date with the core's wire types.\n\
         Regenerate it with:\n  {REGENERATE}"
    );
}

#[test]
fn generated_types_cover_every_tagged_variant() {
    let fresh = generate();
    for tag in client_message_types()
        .iter()
        .chain(server_message_types().iter())
    {
        assert!(
            fresh.contains(&format!("\"type\": \"{tag}\"")),
            "no TypeScript variant tagged {tag}"
        );
    }
}

/// The serde shapes the wire uses, or may use after a merge, come out of
/// ts-rs as serde reads and writes them.
#[test]
fn ts_rs_follows_serde_attributes() {
    #[derive(serde::Serialize, serde::Deserialize, TS)]
    struct Extra {
        note: String,
    }

    #[derive(serde::Serialize, serde::Deserialize, TS)]
    struct Line {
        id: u64,
    }

    #[derive(serde::Serialize, serde::Deserialize, TS)]
    #[serde(rename_all = "snake_case")]
    enum Mode {
        EdgesFirst,
    }

    #[derive(serde::Serialize, serde::Deserialize, TS)]
    #[serde(tag = "type", rename_all = "snake_case")]
    #[allow(dead_code)]
    enum Message {
        DoThing {
            #[serde(default)]
            count: u64,
            maybe: Option<String>,
            #[serde(default, skip_serializing_if = "Option::is_none")]
            sometimes: Option<u32>,
            mode: Mode,
            #[serde(flatten)]
            extra: Extra,
        },
        Bare,
        Wrapped(Line),
    }

    let cfg = Config::new().with_large_int("number");
    assert_eq!(Mode::decl(&cfg), r#"type Mode = "edges_first";"#);
    assert_eq!(
        Message::decl(&cfg),
        r#"type Message = { "type": "do_thing", count: number, maybe: string | null, sometimes?: number | null, mode: Mode, note: string, } | { "type": "bare" } | { "type": "wrapped" } & Line;"#
    );
}
